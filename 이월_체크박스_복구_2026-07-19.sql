-- ── ① [먼저 실행] 복구 대상 미리보기 ────────────────────────────────────────
--    "- [x] ... → M/D 이월" 패턴을 가진 노트만 조회. 내용 확인 후 ②를 실행하세요.
SELECT
  id,
  title AS 제목,
  assignee AS 담당자,
  note_date AS 노트날짜,
  content AS 현재내용
FROM work_notes
WHERE deleted_at IS NULL
  AND content ~ '- \[x\] .*→\s*\d{1,2}/\d{1,2}\s*이월'
ORDER BY updated_at DESC;


